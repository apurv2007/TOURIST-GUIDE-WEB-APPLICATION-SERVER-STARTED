    if not validate_email(user_email):
        flash("Invalid Email Format! Please enter a valid email address.", "danger")
        return redirect(url_for("destination_detail", spot_id=spot_id))

    if not validate_phone(user_phone):
        flash("Invalid Phone Number! Must be a 10-digit number starting with 6-9.", "danger")
        return redirect(url_for("destination_detail", spot_id=spot_id))

    if not validate_date(travel_date):
        flash("Invalid Date Format! Please select a valid date.", "danger")
        return redirect(url_for("destination_detail", spot_id=spot_id))

    total_cost = spot_price * num_travelers

    # File I/O + Multithreading (Unit I & II)
    booking_id = save_booking(spot_id, spot_name, user_name, user_email, user_phone, travel_date, num_travelers, total_cost)

    flash(f"Booking Confirmed! Your Booking ID is #{booking_id}. Total Cost: ₹{total_cost:,.2f}", "success")
    return redirect(url_for("bookings"))


